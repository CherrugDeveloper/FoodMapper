import type { ExerciseAnim } from '../components/ExerciseFigure';

export type EquipmentType = 
  | 'bodyweight' 
  | 'dumbbells' 
  | 'bands' 
  | 'machine' 
  | 'barbell' 
  | 'kettlebell' 
  | 'pullup_bar' 
  | 'bench'
  | 'cardio_machine';

export type ExerciseCategory = 
  | 'cardio' 
  | 'strength_upper' 
  | 'strength_lower' 
  | 'strength_core' 
  | 'mobility' 
  | 'yoga' 
  | 'hiit' 
  | 'stretching'
  | 'rest';

export type DifficultyLevel = 'beginner' | 'intermediate' | 'advanced';

export interface ExerciseInfo {
  id: string;
  name: string; // Chiave i18n: workout_{id}_name
  anim: ExerciseAnim;
  category: ExerciseCategory;
  equipment: EquipmentType[];
  /** MET value (Metabolic Equivalent of Task) - per calcolo calorie: MET * peso_kg * ore */
  met: number;
  /** Calorie al minuto per persona 70kg (stima basata su MET) */
  caloriesPerMinute: number;
  intensity: 'low' | 'moderate' | 'high' | 'very_high';
  difficulty: DifficultyLevel;
  targetMuscles: string[]; // Chiavi i18n: muscles.{muscle}
  secondaryMuscles?: string[];
  instructions: string; // Chiave i18n: workout_{id}_instructions
  steps: string[]; // Chiavi i18n: workout_{id}_step_1, workout_{id}_step_2, ...
  gifUrl?: string;
  fallbackImageUrl?: string;
  /** Durata consigliata in minuti per sessione standard */
  recommendedDurationMin: number;
  /** Serie x ripetizioni consigliate (per forza) o durata (per cardio/plank) */
  recommendedSetsReps: string;
  /** Note aggiuntive */
  notes?: string;
}

export interface WorkoutSuggestionProfile {
  moreCardio: boolean;
  moreStrength: boolean;
  lowImpact: boolean;
  reasonKey: string;
}

export interface WorkoutPlanInput {
  activityLevel: 'sedentary' | 'lightly_active' | 'moderately_active' | 'very_active' | 'extremely_active';
  goal: 'weight_loss' | 'muscle_gain' | 'maintenance' | 'health' | 'endurance';
  preferences: ('cardio' | 'strength' | 'yoga' | 'mixed')[];
  equipment: EquipmentType[];
  daysPerWeek: number; // 3-6
  sessionDurationMin: number; // 20-60
  intensity: 'low' | 'moderate' | 'high';
  focusAreas?: string[]; // es. ['core', 'glutes', 'upper_body']
}

export interface WeeklyWorkoutPlan {
  days: Record<string, DayWorkout>;
  totalSessionsPerWeek: number;
  estimatedWeeklyCaloriesBurned: number;
  notes: string;
}

export interface DayWorkout {
  day: string;
  exercises: PlannedExercise[];
  totalDurationMin: number;
  estimatedCaloriesBurned: number;
  focus: string;
}

export interface PlannedExercise {
  exerciseId: string;
  sets?: number;
  reps?: string; // es. "12-15" o "30 sec"
  durationMin?: number;
  restSec?: number;
  order: number;
  notes?: string;
}

