// Helper functions
export function getExercisesByCategory(category: ExerciseCategory): ExerciseInfo[] {
  return Object.values(EXERCISES).filter(ex => ex.category === category);
}

export function getExercisesByEquipment(equipment: EquipmentType): ExerciseInfo[] {
  return Object.values(EXERCISES).filter(ex => ex.equipment.includes(equipment));
}

export function getExercisesByDifficulty(difficulty: DifficultyLevel): ExerciseInfo[] {
  return Object.values(EXERCISES).filter(ex => ex.difficulty === difficulty);
}

export function getExercisesByIntensity(intensity: ExerciseInfo['intensity']): ExerciseInfo[] {
  return Object.values(EXERCISES).filter(ex => ex.intensity === intensity);
}

export function getExercisesByTargetMuscle(muscle: string): ExerciseInfo[] {
  return Object.values(EXERCISES).filter(ex => 
    ex.targetMuscles.includes(muscle) || ex.secondaryMuscles?.includes(muscle)
  );
}

export function calculateExerciseCalories(exerciseId: string, weightKg: number, durationMin: number): number {
  const exercise = EXERCISES[exerciseId];
  if (!exercise) return 0;
  // MET * peso_kg * (durata_min / 60)
  return Math.round(exercise.met * weightKg * (durationMin / 60));
}

export function calculateWorkoutCalories(exercises: PlannedExercise[], weightKg: number): number {
  return exercises.reduce((total, ex) => {
    const exercise = EXERCISES[ex.exerciseId];
    if (!exercise) return total;
    const duration = ex.durationMin || exercise.recommendedDurationMin;
    return total + calculateExerciseCalories(ex.exerciseId, weightKg, duration);
  }, 0);
}
